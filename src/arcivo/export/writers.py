def iso(ts: int | None, tz=None) -> str | None:  # type: ignore[no-untyped-def]
    return datetime.fromtimestamp(ts, tz=tz).isoformat() if ts else None


class Writer:
    ext = "txt"

    def __init__(self, path: Path, fields: list[str], title: str) -> None:
        self.path = path
        self.fields = fields
        self.title = title
        self.fh: TextIO = open(path, "w", encoding="utf-8", newline="")  # noqa: SIM115 (streaming writer, closed in close())
        self.count = 0

    def write(self, rec: dict[str, Any]) -> None:
        raise NotImplementedError

    def close(self) -> None:
        self.fh.close()


class JsonWriter(Writer):
    ext = "json"

    def __init__(self, path: Path, fields: list[str], title: str) -> None:
        super().__init__(path, fields, title)
        meta = {"generator": f"{APP_NAME} {__version__}", "title": title, "exported_at": datetime.now().astimezone().isoformat()}
        self.fh.write('{"meta": ' + json.dumps(meta, ensure_ascii=False) + ', "messages": [\n')

    def write(self, rec: dict[str, Any]) -> None:
        self.fh.write((",\n" if self.count else "") + json.dumps({k: rec.get(k) for k in self.fields}, ensure_ascii=False))
        self.count += 1

    def close(self) -> None:
        self.fh.write("\n]}\n")
        super().close()


class JsonlWriter(Writer):
    ext = "jsonl"

    def write(self, rec: dict[str, Any]) -> None:
        self.fh.write(json.dumps({k: rec.get(k) for k in self.fields}, ensure_ascii=False) + "\n")
        self.count += 1


class CsvWriter(Writer):
    ext = "csv"

    def __init__(self, path: Path, fields: list[str], title: str) -> None:
        super().__init__(path, fields, title)
        self.fh.write("\ufeff")  # BOM so Excel opens UTF-8 (Persian) correctly
        self.w = csv.DictWriter(self.fh, fieldnames=fields, extrasaction="ignore")
        self.w.writeheader()

    def write(self, rec: dict[str, Any]) -> None:
        row = {k: ("; ".join(v) if isinstance(v, list) else v) for k, v in rec.items()}
        # neutralise spreadsheet formula injection
        for k, v in row.items():
            if isinstance(v, str) and v[:1] in ("=", "+", "-", "@"):
                row[k] = "'" + v
        self.w.writerow(row)
        self.count += 1


class TxtWriter(Writer):
    ext = "txt"

    def __init__(self, path: Path, fields: list[str], title: str) -> None:
        super().__init__(path, fields, title)
        self.fh.write(f"{title}\n{'=' * len(title)}\n\n")

    def write(self, rec: dict[str, Any]) -> None:
        head = f"#{rec.get('id')}  {rec.get('date') or ''}  [{rec.get('media_type')}]"
        if rec.get("sender_name"):
            head += f"  — {rec['sender_name']}"
        lines = [head]
        for k in self.fields:
            if k in ("id", "date", "media_type", "sender_name", "text"):
                continue
            v = rec.get(k)
            if v not in (None, "", [], 0, False):
                lines.append(f"  {k}: {'; '.join(v) if isinstance(v, list) else v}")
        if "text" in self.fields and rec.get("text"):
            lines.append("")
            lines.extend("  " + ln for ln in str(rec["text"]).splitlines())
        self.fh.write("\n".join(lines) + "\n\n" + "-" * 60 + "\n\n")
        self.count += 1


class MarkdownWriter(Writer):
    ext = "md"

    def __init__(self, path: Path, fields: list[str], title: str) -> None:
        super().__init__(path, fields, title)
        self.fh.write(f"# {title}\n\n_Generated by {APP_NAME} {__version__}_\n\n")

    def write(self, rec: dict[str, Any]) -> None:
        self.fh.write(f"### #{rec.get('id')} · {rec.get('date') or ''} · `{rec.get('media_type')}`\n\n")
        if rec.get("exported_file"):
            self.fh.write(f"📎 [{rec.get('file_name') or rec['exported_file']}]({rec['exported_file'].replace(' ', '%20')})\n\n")
        if "text" in self.fields and rec.get("text"):
            self.fh.write(str(rec["text"]).replace("\n", "  \n") + "\n\n")
        meta = []
        for k in self.fields:
            v = rec.get(k)
            if k in ("id", "date", "media_type", "text", "exported_file") or v in (None, "", [], False):
                continue
            meta.append(f"**{k}**: {'; '.join(map(str, v)) if isinstance(v, list) else v}")
        if meta:
            self.fh.write(" · ".join(meta) + "\n\n")
        self.fh.write("---\n\n")
        self.count += 1


