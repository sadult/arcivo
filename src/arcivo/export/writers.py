class HtmlWriter(Writer):
    ext = "html"
    IMAGE_EXT = {"jpg", "jpeg", "png", "webp", "gif"}

    def __init__(self, path: Path, fields: list[str], title: str, lang: str = "en") -> None:
        super().__init__(path, fields, title)
        sub = f"{APP_NAME} {__version__} · {datetime.now().astimezone():%Y-%m-%d %H:%M}"
        self.fh.write(_HTML_HEAD.format(lang=lang, title=html.escape(title),
                                        subtitle=html.escape(sub)))

    def write(self, rec: dict[str, Any]) -> None:
        e = html.escape
        parts = [f'<article class="m" id="m{rec.get("id")}"><div class="h"><span class="badge">{e(str(rec.get("media_type")))}</span>'
                 f'<span>#{rec.get("id")}</span><span>{e(str(rec.get("date") or ""))}</span>']
        if rec.get("sender_name"):
            parts.append(f"<span>{e(str(rec['sender_name']))}</span>")
        if rec.get("chat_name"):
            parts.append(f"<span>· {e(str(rec['chat_name']))}</span>")
        parts.append("</div>")
        f = rec.get("exported_file")
        if f:
            href = e(f.replace("\\", "/"))
            if (rec.get("extension") or "").lower() in self.IMAGE_EXT or rec.get("media_type") == "photo":
                parts.append(f'<a href="{href}"><img class="p" loading="lazy" src="{href}" alt=""></a>')
            else:
                parts.append(f'<div>📎 <a href="{href}">{e(str(rec.get("file_name") or f))}</a></div>')
        if "text" in self.fields and rec.get("text"):
            parts.append(f'<div class="t">{e(str(rec["text"]))}</div>')
        meta = [(k, rec.get(k)) for k in self.fields if k not in ("id", "date", "media_type", "text", "sender_name", "chat_name",
                                                                  "exported_file") and rec.get(k) not in (None, "", [], False)]
        if meta:
            items = []
            for k, v in meta:
                if k == "links" and isinstance(v, list):
                    val = " ".join(f'<a href="{e(u)}" rel="noopener">{e(u)}</a>' for u in v)
                else:
                    val = e("; ".join(map(str, v)) if isinstance(v, list) else str(v))
                items.append(f"<dt>{e(k)}</dt><dd>{val}</dd>")
            parts.append("<dl>" + "".join(items) + "</dl>")
        parts.append("</article>\n")
        self.fh.write("".join(parts))
        self.count += 1

    def close(self) -> None:
        self.fh.write(f"</main><footer style='text-align:center;color:var(--muted);padding:24px'>{self.count} messages</footer></body></html>")
        super().close()


