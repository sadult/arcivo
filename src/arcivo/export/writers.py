def record_from_row(row: Any, *, links: list[str], tags: list[str], exported_file: str | None, tz=None) -> dict[str, Any]:  # type: ignore[no-untyped-def]
    d = dict(row)
    return {
        "id": d["id"], "date": iso(d.get("date_ts"), tz), "edit_date": iso(d.get("edit_ts"), tz), "media_type": d.get("media_type"),
        "category": d.get("category"), "text": d.get("text") or "", "file_name": d.get("file_name"), "extension": d.get("extension"),
        "mime_type": d.get("mime_type"), "file_size": d.get("file_size"), "duration": d.get("duration"), "width": d.get("width"),
        "height": d.get("height"), "performer": d.get("performer"), "audio_title": d.get("audio_title"),
        "sender_id": d.get("sender_id"), "sender_name": d.get("sender_name"), "sender_username": d.get("sender_username"),
        "chat_id": d.get("chat_id"), "chat_name": d.get("chat_name"), "chat_type": d.get("chat_type"),
        "is_forward": bool(d.get("is_forward")), "fwd_date": iso(d.get("fwd_date_ts"), tz), "fwd_msg_id": d.get("fwd_msg_id"),
        "reply_to_id": d.get("reply_to_id"), "grouped_id": d.get("grouped_id"), "links": links, "tags": tags,
        "views": d.get("views"), "media_id": d.get("media_id"), "dc_id": d.get("dc_id"), "exported_file": exported_file,
    }
